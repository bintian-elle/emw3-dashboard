type Props = { customer: boolean; t: (text: LocalizedText) => string };
function CombinationTags({ elements, t }: { elements: CombinationElement[]; t: Props["t"] }) {
  const tags = <span className={`${styles.combination} ${styles.candidateDifferences}`}>
    {elements.map(element => <span key={element.key} data-dimension={element.key}>
      <span>{t(element.name)}</span> <strong><code>{element.code}</code> {t(element.label)}</strong>
    </span>)}
  </span>;
  if (elements.length < 2) return tags;
  return <details className={styles.compactCombination}>
    <summary>
      {tags}
      <span className={styles.combinationChevron} title={t(["Show or hide combination details", "展开或收起组合详情"])}>
        <ChevronDown size={16} aria-hidden="true" />
        <span className="sr-only">{t(["Show or hide combination details", "展开或收起组合详情"])}</span>
      </span>
    </summary>
  </details>;
}

export function ScriptCandidates({ customer, canReview, t }: Props & { canReview: boolean }) {
  const path = scriptLabSectionPath("candidates", customer);
  const params = useSearchParams();
  const jobs = useVideoJobs(customer);
  const batches = jobs.filter(job => job.mode === "script" && job.status === "completed")
    .sort((a, b) => Date.parse(b.finished_at ?? b.submitted_at) - Date.parse(a.finished_at ?? a.submitted_at));
  const specifiedBatch = params.get("batch");
  const requestedBatch = specifiedBatch === "DEMO-001" ? null : specifiedBatch;
  const batchId = requestedBatch ?? batches[0]?.batch_id;
  const generated = batchId && videoIdPattern.test(batchId) ? batchId : null;
  const { batch: generatedBatch, failed: batchFailed } = useVideoBatch(customer, generated);
  const [loginPrompt, setLoginPrompt] = useState(0);
  const activeBatch = batches.find(job => job.batch_id === generated);

  return <div className={styles.scriptCandidateStack}>
    <section aria-label={t(["Batches", "批次"])}>
      <h2 className={styles.candidateGroupHeading}>{t(["Batches", "批次"])}</h2>
      <nav className={styles.scriptBatchList} aria-label={t(["Candidate sources", "剧本来源"])}>
        {batches.map(job =>
          <Link key={job.id} href={`${path}?${new URLSearchParams({ batch: job.batch_id, script: job.first_script_id ?? "" })}`}
            aria-current={generated === job.batch_id ? "true" : undefined}>
            <strong><time dateTime={job.finished_at ?? job.submitted_at}>{batchName(job.finished_at ?? job.submitted_at)}</time></strong>
          </Link>)}
      </nav>
      <Card className={`${styles.panel} ${styles.candidateTabPanel}`}>
        {activeBatch && <div className={styles.candidateBatchMetadata}>
          <span>{t(activeBatch.combination).split(" × ", 3).join(" × ")}</span>
          <span>{t([`${activeBatch.total} script combinations`, `${activeBatch.total} 个剧本组合`])}</span>
          <span>{t([`Generated by ${activeBatch.requested_name}`, `由 ${activeBatch.requested_name} 生成`])}</span>
        </div>}
        {generated && !batchFailed ? <GeneratedCandidates key={generated} batch={generatedBatch} activeId={params.get("script")}
          path={path} customer={customer} canReview={canReview} t={t} signIn={() => setLoginPrompt(value => value + 1)} />
        : <p>{requestedBatch ? t(["This batch is unavailable. Choose a batch from the list.", "这个批次不可用，请从列表选择一个批次。"])
          : t(["No AI-generated batches yet.", "暂无 AI 生成批次。"])}</p>}
      </Card>
    </section>
    {customer && loginPrompt > 0 && <div hidden>
      <CustomerAccount key={loginPrompt} email={null} autoOpen returnTo={path} />
    </div>}
  </div>;
}

function matchingReport(report: ComplianceReport | undefined, batch: string, kind: "script" | "storyboard", id: string, revision: string) {
  return report?.status === "completed" && sameComplianceTarget(report, {
    batch_id: batch, artifact_kind: kind, artifact_id: id, artifact_revision: revision,
  }) ? report : undefined;
}

function ExampleMark({ t }: Pick<Props, "t">) {
  return <span className={styles.exampleMark} role="img" aria-label={t(["Excellent example", "优秀案例"])}
    title={t(["Excellent example", "优秀案例"])}><Award size={16} aria-hidden="true" /></span>;
}

function GeneratedCandidates({ batch, activeId, path, customer, canReview, t, signIn }: {
  batch?: VideoBatch; activeId: string | null; path: string;
  customer: boolean; canReview: boolean; t: Props["t"]; signIn: () => void;
}) {
  const [selected, setSelected] = useState<Set<string>>(new Set());
  const [savedExamples, setSavedExamples] = useState<Set<string>>(new Set());
  const active = batch?.scripts.find(script => script.id === activeId) ?? batch?.scripts[0];
  if (!batch || !active) return <p role="status">{t(["Loading scripts…", "正在读取剧本…"])}</p>;
  const board = batch.storyboards?.find(item => item.script_id === active.id && item.script_revision === active.revision);
  const matchedScriptReport = matchingReport(active.compliance, batch.batch_id, "script", active.id, active.revision);
  const scriptReport = matchedScriptReport?.storyboard_revision && matchedScriptReport.storyboard_revision !== board?.revision
    ? undefined : matchedScriptReport;
  const storyboardReport = board && matchingReport(board.compliance, board.storage_batch_id ?? batch.batch_id, "storyboard", board.id, board.revision);
  const reports = [scriptReport, storyboardReport].filter(report => report !== undefined);
  const execution = active.combination.filter(element => ["SCN", "CAST", "STY", "PLT", "LEN"].includes(element.key));
  const titles = new Map(batch.scripts.map(script => [script.id, script.pain]));
  const actionIds = selected.size ? [...selected] : [active.id];
  const actions = <ExampleActions key={JSON.stringify(actionIds)} batch={batch.batch_id}
    ids={actionIds} customer={customer} canManage={canReview} signIn={signIn}
    onSavedChange={setSavedExamples} titles={titles} t={t} />;


  return <section className={styles.candidateScriptGroup}>
      <div className={styles.panelHeader}>
        <h2>{t([`Scripts (${batch.scripts.length})`, `剧本名单（${batch.scripts.length} 条）`])}</h2>
        <div className={styles.scriptListActions}>
          <SelectionToggle checked={selected} ids={batch.scripts.map(script => script.id)} onChange={setSelected} t={t} />
          {selected.size > 0 && actions}
        </div>
      </div>
      <ul className={styles.scriptNames}>{batch.scripts.map(script => <li key={script.id}>
        <input type="checkbox" aria-label={t(script.pain)} checked={selected.has(script.id)}
          onChange={event => setSelected(previous => {
            const next = new Set(previous);
            if (event.target.checked) next.add(script.id); else next.delete(script.id);
            return next;
          })} />
        <Link href={`${path}?${new URLSearchParams({ batch: batch.batch_id, script: script.id })}`} scroll={false}
          aria-current={script.id === active.id ? "true" : undefined}><strong>{t(script.pain)}{savedExamples.has(script.id) && <ExampleMark t={t} />}</strong></Link>
      </li>)}</ul>
    <section aria-label={t(["Script details", "剧本详情"])}>
      <Card className={`${styles.panel} ${styles.candidateTabPanel}`}>
        <div className={styles.scriptDetailHeader}>
          <h2>{t(active.pain)}{savedExamples.has(active.id) && <ExampleMark t={t} />}</h2>
          {selected.size === 0 && actions}
        </div>
        <ScriptDetailSections t={t}
          combination={<CombinationTags elements={active.combination} t={t} />}
          opening={<ScriptCopy copy={active.copy.hook} language={active.language} t={t} />}
          body={<ol className={styles.baselineBody}>
            <li><ScriptCopy copy={active.copy.body} language={active.language} t={t} /></li>
            <li><strong>{t(["Closing CTA", "结尾 CTA"])}</strong><ScriptCopy copy={active.copy.cta} language={active.language} t={t} /></li>
          </ol>}
          storyboard={board ? <SceneTable storyboard={board.storyboard} t={t} />
            : <p className={styles.muted}>{t(["Storyboard pending", "未生成分镜"])}</p>}
          rationale={<CreativeRationale logic={active.rationale} storyboardLogic={board?.storyboard.logic} includeExecution={false} t={t} />}
          sceneExecution={execution.length > 0 && <CombinationTags elements={execution} t={t} />}
          footer={<>
            {reports.length > 0 && <CompletedComplianceReport report={reports[0]} additional={reports.slice(1)} t={t} />}
            {!scriptReport && <p className={styles.muted}>{active.compliance_failed
              ? t(["Script self-check did not complete", "剧本自检未完成"]) : t(["Script self-check in progress", "剧本自检中"])}</p>}
            {board && !board.compliance_in_script && !storyboardReport && <p className={styles.muted}>{board.compliance_failed
              ? t(["Storyboard self-check did not complete", "分镜自检未完成"]) : t(["Storyboard self-check in progress", "分镜自检中"])}</p>}
          </>}
        />
      </Card>
    </section>
  </section>;
}
